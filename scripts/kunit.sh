#!/usr/bin/env bash
# kunit.sh — run the kmod KUnit suites (kmod/*_kunit.c) in UML or qemu.
#
# Usage:
#   KSRC=/path/to/linux-6.12+ scripts/kunit.sh [kunit.py run args...]
#   KSRC=... scripts/kunit.sh --raw_output=all     # full console log
#   KSRC=... scripts/kunit.sh 's3fs_ebpf_vfs*'     # a filter glob
#   KSRC=... scripts/kunit.sh --arch=x86_64 --qemu_args='-smp 4'
#                                   # qemu instead of UML: real SMP and JIT
#
# Needs a kernel source tree (>= 6.12, the kmod's minimum) with
# tools/testing/kunit/kunit.py; distro headers are not enough.  The module
# cannot be loaded into the UML kernel (there is no root fs), so the kmod
# sources are linked into $KSRC/fs/s3fs_ebpf_kunit/ and built in (obj-y)
# with -DS3FS_KUNIT, which pulls the test files into the translation units
# whose static functions they test.  $KSRC/fs/Makefile gets one obj-y line;
# nothing else in the tree is touched.  Build output goes to $BUILD_DIR
# (default: $KSRC/.kunit-s3fs-<arch>) so a normal kernel build in $KSRC is
# not disturbed.  kmod/.kunitconfig turns on lockdep, KASAN and friends.
#
# The module's init (kfunc/struct_ops registration) may fail in UML (no BTF);
# that is logged and does not affect the suites, which test the data
# structures directly and set up the state they need.
#
# Without a tree at hand, `make -C kmod KDIR=... KUNIT=1` builds the module
# with the suites against a kernel that has CONFIG_KUNIT; loading that
# module runs them (results in dmesg / debugfs kunit/).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
KSRC="${KSRC:?set KSRC to a Linux source tree (>= 6.12)}"
KSRC="$(cd "$KSRC" && pwd)"
ARCH=um
for a in "$@"; do
	case "$a" in --arch=*) ARCH="${a#--arch=}" ;; esac
done
BUILD_DIR="${BUILD_DIR:-$KSRC/.kunit-s3fs-$ARCH}"
CONFIGS=(--kunitconfig="$ROOT/kmod/.kunitconfig")
# UML has one CPU; elsewhere build SMP so the concurrency cases run in
# parallel (pass --qemu_args='-smp N').
if [[ "$ARCH" == um ]]; then
	CONFIGS+=(--kunitconfig="$ROOT/kmod/kunit-uml.config")
else
	CONFIGS+=(--kconfig_add=CONFIG_SMP=y)
fi
JOBS="${JOBS:-$(nproc)}"

# What the kernel build itself needs (kconfig is generated with flex/bison).
missing=()
for c in gcc make flex bison bc python3; do
	command -v "$c" >/dev/null || missing+=("$c")
done
if ((${#missing[@]})); then
	echo "kunit.sh: missing ${missing[*]} (Ubuntu: sudo apt install build-essential flex bison bc)" >&2
	exit 1
fi
# Kconfig runs `pahole --version`; a pahole that is installed but broken
# (e.g. a source build whose libdwarves is not in the ld cache) prints
# nothing and kconfig fails with "init/Kconfig: syntax error".  The suites
# do not need BTF, so build as if pahole were absent.
MAKE_OPTS=()
if command -v pahole >/dev/null && ! pahole --version >/dev/null 2>&1; then
	echo "kunit.sh: pahole is installed but does not run ($(pahole --version 2>&1 | head -n1)); building without it" >&2
	MAKE_OPTS+=(--make_options=PAHOLE=/nonexistent/pahole)
fi

[[ -x "$KSRC/tools/testing/kunit/kunit.py" ]] ||
	{ echo "kunit.sh: $KSRC/tools/testing/kunit/kunit.py not found" >&2; exit 1; }

DIR="$KSRC/fs/s3fs_ebpf_kunit"
mkdir -p "$DIR"
for f in "$ROOT"/kmod/*.[ch]; do
	ln -sf "$f" "$DIR/$(basename "$f")"
done
cat > "$DIR/Makefile" <<EOF
# Generated by s3fs-ebpf scripts/kunit.sh — do not edit.
S3FS_KMOD := $ROOT/kmod
include \$(S3FS_KMOD)/Kbuild
obj-y += \$(obj-m)
obj-m :=
s3fs_kfunc-y := \$(s3fs_kfunc-objs)
ccflags-y += -I\$(S3FS_KMOD) -I\$(S3FS_KMOD)/../include -DS3FS_KUNIT
EOF
grep -qx 'obj-y += s3fs_ebpf_kunit/' "$KSRC/fs/Makefile" ||
	echo 'obj-y += s3fs_ebpf_kunit/' >> "$KSRC/fs/Makefile"

cd "$KSRC"
exec python3 tools/testing/kunit/kunit.py run \
	--build_dir="$BUILD_DIR" \
	"${CONFIGS[@]}" \
	${MAKE_OPTS[@]+"${MAKE_OPTS[@]}"} \
	--jobs="$JOBS" \
	"$@"
